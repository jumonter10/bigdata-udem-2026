-- Suite de controles de integridad y reconciliación.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE SCHEMA CURSO.T1;

WITH controles AS (
    SELECT 'Filas del hecho' AS CONTROL,
           COUNT(*) AS ACTUAL, 46715 AS ESPERADO
    FROM FACT_VIAJES_DIA
    UNION ALL
    SELECT 'Viajes totales', SUM(VIAJES), 60268466 FROM FACT_VIAJES_DIA
    UNION ALL
    SELECT 'Grupos duplicados', COUNT(*), 0 FROM (
        SELECT FECHA, ZONA_KEY, EMPRESA_KEY FROM FACT_VIAJES_DIA
        GROUP BY FECHA, ZONA_KEY, EMPRESA_KEY HAVING COUNT(*) > 1
    )
    UNION ALL
    SELECT 'Hechos sin dimension', COUNT(*), 0
    FROM FACT_VIAJES_DIA F
    LEFT JOIN DIM_FECHA D ON F.FECHA = D.FECHA
    LEFT JOIN DIM_ZONA Z ON F.ZONA_KEY = Z.ZONA_KEY
    LEFT JOIN DIM_EMPRESA E ON F.EMPRESA_KEY = E.EMPRESA_KEY
    WHERE D.FECHA IS NULL OR Z.ZONA_KEY IS NULL OR E.EMPRESA_KEY IS NULL
    UNION ALL
    SELECT 'Diferencia de filas contra origen',
        ABS((SELECT COUNT(*) FROM FACT_VIAJES_DIA)
          - (SELECT COUNT(*) FROM CURSO.LAB4.DAILY_ZONE_METRICS)), 0
    UNION ALL
    SELECT 'Diferencia de viajes contra origen',
        ABS((SELECT SUM(VIAJES) FROM FACT_VIAJES_DIA)
          - (SELECT SUM(VIAJES) FROM CURSO.LAB4.DAILY_ZONE_METRICS)), 0
    UNION ALL
    SELECT 'Fechas del calendario', COUNT(*), 91 FROM DIM_FECHA
    UNION ALL
    SELECT 'Zonas depuradas', COUNT(*), 262 FROM DIM_ZONA
    UNION ALL
    SELECT 'Empresas', COUNT(*), 2 FROM DIM_EMPRESA
    UNION ALL
    SELECT 'Claves de zona duplicadas',
        COUNT(*) - COUNT(DISTINCT ZONA_KEY), 0 FROM DIM_ZONA
    UNION ALL
    SELECT 'Nombres de zona duplicados',
        COUNT(*) - COUNT(DISTINCT ZONA), 0 FROM DIM_ZONA
    UNION ALL
    SELECT 'Claves de empresa duplicadas',
        COUNT(*) - COUNT(DISTINCT EMPRESA_KEY), 0 FROM DIM_EMPRESA
    UNION ALL
    SELECT 'Fechas duplicadas',
        COUNT(*) - COUNT(DISTINCT FECHA), 0 FROM DIM_FECHA
)
SELECT CONTROL, ACTUAL, ESPERADO,
       IFF(ACTUAL = ESPERADO, 'OK', 'REVISAR') AS RESULTADO
FROM controles ORDER BY CONTROL;
