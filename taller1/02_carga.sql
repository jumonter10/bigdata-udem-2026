USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE SCHEMA CURSO.T1;

-- Vaciar antes de insertar hace repetible la carga sin duplicados.
TRUNCATE TABLE FACT_VIAJES_DIA;
TRUNCATE TABLE DIM_ZONA;
TRUNCATE TABLE DIM_EMPRESA;
TRUNCATE TABLE DIM_FECHA;

INSERT INTO DIM_ZONA
SELECT ROW_NUMBER() OVER (ORDER BY ZONA), ZONA, BOROUGH, SERVICE_ZONE
FROM (
    SELECT DISTINCT ZONA, BOROUGH, SERVICE_ZONE
    FROM CURSO.LAB4.DIM_ZONA
);

INSERT INTO DIM_EMPRESA
SELECT ROW_NUMBER() OVER (ORDER BY EMPRESA), EMPRESA
FROM (
    SELECT DISTINCT EMPRESA
    FROM CURSO.LAB4.DAILY_ZONE_METRICS
);

INSERT INTO DIM_FECHA
WITH rango AS (
    SELECT MIN(FECHA) AS INICIO, MAX(FECHA) AS FIN
    FROM CURSO.LAB4.DAILY_ZONE_METRICS
),
calendario AS (
    SELECT DATEADD(
        'day', ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1, INICIO
    )::DATE AS FECHA
    FROM rango, TABLE(GENERATOR(ROWCOUNT => 400))
    QUALIFY FECHA <= FIN
),
lluvia AS (
    SELECT FECHA, MAX(LLUVIA_MM) AS LLUVIA_MM
    FROM CURSO.LAB4.DAILY_ZONE_METRICS
    GROUP BY FECHA
)
SELECT
    C.FECHA, YEAR(C.FECHA), MONTH(C.FECHA),
    DATE_TRUNC('month', C.FECHA)::DATE,
    DAYOFWEEKISO(C.FECHA),
    DAYOFWEEKISO(C.FECHA) IN (6, 7),
    F.FECHA IS NOT NULL,
    F.NOMBRE,
    L.LLUVIA_MM
FROM calendario C
LEFT JOIN lluvia L ON C.FECHA = L.FECHA
LEFT JOIN CURSO.LAB4.FESTIVOS_2024 F ON C.FECHA = F.FECHA;

INSERT INTO FACT_VIAJES_DIA
SELECT
    G.FECHA, Z.ZONA_KEY, E.EMPRESA_KEY,
    G.VIAJES, G.INGRESO_TOTAL,
    G.PROPINA_PROMEDIO * G.VIAJES,
    G.DISTANCIA_PROMEDIO * G.VIAJES
FROM CURSO.LAB4.DAILY_ZONE_METRICS G
JOIN DIM_ZONA Z ON G.ZONA = Z.ZONA
JOIN DIM_EMPRESA E ON G.EMPRESA = E.EMPRESA;

SELECT COUNT(*) AS FILAS, SUM(VIAJES) AS VIAJES
FROM FACT_VIAJES_DIA;
-- Esperado: 46715 filas y 60268466 viajes.
