-- GRANO: una fila por fecha, zona y empresa.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
CREATE SCHEMA IF NOT EXISTS CURSO.T1;
USE SCHEMA CURSO.T1;

-- La unicidad se comprueba en 04_chequeos.sql.
-- Las claves numéricas se generan de forma determinista en cada carga.
CREATE OR REPLACE TABLE DIM_ZONA (
    ZONA_KEY NUMBER NOT NULL,
    ZONA VARCHAR NOT NULL,
    BOROUGH VARCHAR,
    SERVICE_ZONE VARCHAR
);

CREATE OR REPLACE TABLE DIM_EMPRESA (
    EMPRESA_KEY NUMBER NOT NULL,
    EMPRESA VARCHAR NOT NULL
);

CREATE OR REPLACE TABLE DIM_FECHA (
    FECHA DATE NOT NULL,
    ANIO NUMBER,
    MES NUMBER,
    MES_INICIO DATE,
    DIA_SEMANA NUMBER,
    ES_FIN_SEMANA BOOLEAN,
    ES_FESTIVO BOOLEAN,
    NOMBRE_FESTIVO VARCHAR,
    LLUVIA_MM FLOAT
);

-- La lluvia pertenece a DIM_FECHA, no al hecho.
CREATE OR REPLACE TABLE FACT_VIAJES_DIA (
    FECHA DATE NOT NULL,
    ZONA_KEY NUMBER NOT NULL,
    EMPRESA_KEY NUMBER NOT NULL,
    VIAJES NUMBER(38,0),
    INGRESO_TOTAL FLOAT,
    PROPINA_TOTAL_ESTIMADA FLOAT,
    DISTANCIA_TOTAL_ESTIMADA FLOAT
);
